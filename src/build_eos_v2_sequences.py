import sys
import json
import time
from pathlib import Path
from datetime import datetime
import numpy as np
from tokenizers import Tokenizer

sys.stdout.reconfigure(encoding="utf-8")

PROJECT_DIR = Path("D:/DEEP-LEARNING-PROJECT")
sys.path.insert(0, str(PROJECT_DIR / "src"))

# Paths
INPUT_DIR = PROJECT_DIR / "data" / "processed" / "conversation_paths"
OUTPUT_DIR = PROJECT_DIR / "data" / "processed" / "training_sequences_eos_v2"
TOKENIZER_PATH = PROJECT_DIR / "tokenizer" / "tokenizer.json"

TRAIN_SOURCE = INPUT_DIR / "train_paths.jsonl"
VAL_SOURCE = INPUT_DIR / "validation_paths.jsonl"

TRAIN_TOKENS_OUT = OUTPUT_DIR / "train_tokens.bin"
TRAIN_MASK_OUT = OUTPUT_DIR / "train_mask.bin"
VAL_TOKENS_OUT = OUTPUT_DIR / "validation_tokens.bin"
VAL_MASK_OUT = OUTPUT_DIR / "validation_mask.bin"
METADATA_OUT = OUTPUT_DIR / "dataset_metadata.json"

# Constants
CONTEXT_LENGTH = 1024
VOCAB_SIZE = 8000

PAD_ID = 0
UNK_ID = 1
BOS_ID = 2
EOS_ID = 3
USER_ID = 4
ASSISTANT_ID = 5

def create_loss_mask_v2(token_ids):
    """
    Assistant-only loss mask for EOS v2 format:
    1 = include token in assistant loss (all assistant response tokens + EOS)
    0 = ignore token (prompts, user tokens, padding, etc.)
    """
    mask = np.zeros(len(token_ids), dtype=np.uint8)
    assistant_active = False

    for i, token_id in enumerate(token_ids):
        if token_id == ASSISTANT_ID:
            assistant_active = True
            mask[i] = 1
        elif token_id == EOS_ID:
            if assistant_active:
                mask[i] = 1 # EOS generated by assistant is supervised
            assistant_active = False # immediately inactive after EOS
        elif token_id == USER_ID:
            assistant_active = False
            mask[i] = 0
        elif assistant_active:
            mask[i] = 1

    return mask

def process_paths_file(source_file, tokens_out_file, mask_out_file, name, tokenizer):
    print("=" * 70)
    print(f"PROCESSING {name.upper()} DATASET (EOS V2 FORMAT: 1 CONV = 1 SEQUENCE)")
    print("=" * 70)

    start_time = time.time()
    source_conv_count = 0
    trimmed_trailing_user_count = 0
    total_asst_turns = 0

    orig_total_tokens = 0
    retained_tokens = 0
    discarded_tokens = 0

    pad_tokens_count = 0
    loss_tokens_count = 0
    unmasked_tokens_count = 0

    truncated_conv_count = 0
    untruncated_conv_count = 0

    special_token_counts = {
        "PAD": 0, "BOS": 0, "EOS": 0, "USER": 0, "ASSISTANT": 0
    }

    tree_ids = set()
    token_sequences = []
    mask_sequences = []

    with open(source_file, "r", encoding="utf-8") as f:
        for line_idx, line in enumerate(f):
            conv = json.loads(line)
            tree_ids.add(conv["tree_id"])
            messages = conv["messages"]
            source_conv_count += 1

            # Option 1: Trim trailing unanswered user messages
            orig_msg_count = len(messages)
            while len(messages) > 0 and messages[-1]["role"] == "prompter":
                messages.pop()
                trimmed_trailing_user_count += 1

            if len(messages) == 0:
                raise ValueError(f"Line {line_idx+1}: Conversation has no assistant messages!")
            if messages[-1]["role"] != "assistant":
                raise ValueError(f"Line {line_idx+1}: Conversation does not end with assistant!")

            # Format with explicit [EOS] at the end of every assistant turn
            parts = ["[BOS]"]
            conv_asst_turns = 0
            for msg in messages:
                role = msg["role"]
                text = msg["text"].strip()
                if role == "prompter":
                    parts.append("<|user|>")
                    parts.append(text)
                elif role == "assistant":
                    parts.append("<|assistant|>")
                    parts.append(text)
                    parts.append("[EOS]")
                    conv_asst_turns += 1

            total_asst_turns += conv_asst_turns
            formatted_text = "\n".join(parts)

            encoded = tokenizer.encode(formatted_text)
            token_ids = encoded.ids
            raw_len = len(token_ids)
            orig_total_tokens += raw_len

            if token_ids[0] != BOS_ID:
                raise ValueError(f"Line {line_idx+1}: Sequence does not begin with BOS_ID!")

            # Full mask before padding/truncation
            raw_mask = create_loss_mask_v2(token_ids)

            # Apply 1024 sequence packaging (Design A)
            if raw_len <= CONTEXT_LENGTH:
                untruncated_conv_count += 1
                pad_amount = CONTEXT_LENGTH - raw_len
                seq_tokens = np.pad(token_ids, (0, pad_amount), constant_values=PAD_ID).astype(np.uint16)
                seq_mask = np.pad(raw_mask, (0, pad_amount), constant_values=0).astype(np.uint8)

                pad_tokens_count += pad_amount
                retained_tokens += raw_len
                special_token_counts["PAD"] += pad_amount
            else:
                truncated_conv_count += 1
                seq_tokens = np.array(token_ids[:CONTEXT_LENGTH], dtype=np.uint16)
                seq_mask = raw_mask[:CONTEXT_LENGTH].astype(np.uint8)

                retained_tokens += CONTEXT_LENGTH
                discarded_tokens += (raw_len - CONTEXT_LENGTH)

            # Count special tokens in final packaged sequence
            special_token_counts["BOS"] += int((seq_tokens == BOS_ID).sum())
            special_token_counts["EOS"] += int((seq_tokens == EOS_ID).sum())
            special_token_counts["USER"] += int((seq_tokens == USER_ID).sum())
            special_token_counts["ASSISTANT"] += int((seq_tokens == ASSISTANT_ID).sum())

            seq_loss_tokens = int(seq_mask.sum())
            loss_tokens_count += seq_loss_tokens
            unmasked_tokens_count += (CONTEXT_LENGTH - seq_loss_tokens)

            token_sequences.append(seq_tokens)
            mask_sequences.append(seq_mask)

            if source_conv_count % 5000 == 0:
                print(f"Processed {source_conv_count:,} conversations...")

    output_seq_count = len(token_sequences)
    print(f"\nConversations processed: {source_conv_count:,}")
    print(f"Output sequences:        {output_seq_count:,}")
    print(f"Trimmed user prompts:    {trimmed_trailing_user_count:,}")
    print(f"Total assistant turns:   {total_asst_turns:,}")

    # Convert to contiguous numpy arrays
    token_array = np.vstack(token_sequences).astype(np.uint16)
    mask_array = np.vstack(mask_sequences).astype(np.uint8)

    print(f"Writing binary tokens to: {tokens_out_file}")
    token_array.tofile(tokens_out_file)

    print(f"Writing binary masks to:  {mask_out_file}")
    mask_array.tofile(mask_out_file)

    elapsed = time.time() - start_time
    print(f"Completed in {elapsed:.2f} seconds.")

    total_capacity = output_seq_count * CONTEXT_LENGTH
    real_tokens = total_capacity - pad_tokens_count

    stats = {
        "source_conversations": source_conv_count,
        "output_sequences": output_seq_count,
        "trimmed_trailing_user_messages": trimmed_trailing_user_count,
        "total_assistant_turns": total_asst_turns,
        "distinct_trees": len(tree_ids),
        "context_length": CONTEXT_LENGTH,
        "total_sequence_capacity": total_capacity,
        "real_tokens": real_tokens,
        "real_tokens_pct": (real_tokens / total_capacity) * 100,
        "pad_tokens": pad_tokens_count,
        "pad_tokens_pct": (pad_tokens_count / total_capacity) * 100,
        "avg_pad_tokens_per_seq": pad_tokens_count / output_seq_count,
        "truncated_conversations": truncated_conv_count,
        "truncated_conversations_pct": (truncated_conv_count / source_conv_count) * 100,
        "untruncated_conversations": untruncated_conv_count,
        "untruncated_conversations_pct": (untruncated_conv_count / source_conv_count) * 100,
        "original_total_tokens": orig_total_tokens,
        "retained_tokens": retained_tokens,
        "discarded_tokens": discarded_tokens,
        "loss_tokens_mask_1": loss_tokens_count,
        "loss_tokens_mask_1_pct": (loss_tokens_count / total_capacity) * 100,
        "unmasked_tokens_mask_0": unmasked_tokens_count,
        "unmasked_tokens_mask_0_pct": (unmasked_tokens_count / total_capacity) * 100,
        "special_token_frequencies": special_token_counts,
        "tokens_file_bytes": tokens_out_file.stat().st_size,
        "mask_file_bytes": mask_out_file.stat().st_size,
    }

    return stats, tree_ids

def run_automated_checks(train_stats, val_stats, train_trees, val_trees):
    print("\n" + "=" * 70)
    print("RUNNING AUTOMATED CHECKS ON EOS V2 DATASET")
    print("=" * 70)

    checks = []

    # 1. Tree Overlap Check
    tree_overlap = train_trees.intersection(val_trees)
    check1 = (len(tree_overlap) == 0)
    checks.append({
        "check": "Train/Validation Tree Isolation",
        "passed": check1,
        "details": f"Train trees: {len(train_trees)}, Val trees: {len(val_trees)}, Overlap: {len(tree_overlap)}"
    })
    print(f"[{'PASS' if check1 else 'FAIL'}] Tree Isolation: Overlapping trees = {len(tree_overlap)}")

    # 2. File size and dtype checks
    t_tok_size = TRAIN_TOKENS_OUT.stat().st_size
    t_msk_size = TRAIN_MASK_OUT.stat().st_size
    v_tok_size = VAL_TOKENS_OUT.stat().st_size
    v_msk_size = VAL_MASK_OUT.stat().st_size

    n_train_seq = train_stats["output_sequences"]
    n_val_seq = val_stats["output_sequences"]

    check2_train = (t_tok_size == n_train_seq * CONTEXT_LENGTH * 2) and (t_msk_size == n_train_seq * CONTEXT_LENGTH)
    check2_val = (v_tok_size == n_val_seq * CONTEXT_LENGTH * 2) and (v_msk_size == n_val_seq * CONTEXT_LENGTH)
    check2 = check2_train and check2_val
    checks.append({
        "check": "Binary File Sizes & Dtypes",
        "passed": check2,
        "details": f"Train tokens: {t_tok_size} bytes ({n_train_seq} seqs), Val tokens: {v_tok_size} bytes ({n_val_seq} seqs)"
    })
    print(f"[{'PASS' if check2 else 'FAIL'}] Binary File Sizes: Exact match for uint16 tokens and uint8 masks")

    # 3. Deep sequence verification on sample sequences
    train_tokens = np.memmap(TRAIN_TOKENS_OUT, dtype=np.uint16, mode="r")
    train_mask = np.memmap(TRAIN_MASK_OUT, dtype=np.uint8, mode="r")

    num_samples_to_check = min(1000, n_train_seq)
    pad_exclusion_pass = True
    bos_pos0_pass = True
    user_unmasked_pass = True
    eos_supervised_pass = True
    shifted_alignment_pass = True
    pad_suffix_pass = True

    for seq_idx in range(num_samples_to_check):
        start = seq_idx * CONTEXT_LENGTH
        end = start + CONTEXT_LENGTH
        s = train_tokens[start:end]
        m = train_mask[start:end]

        # Check BOS at 0
        if s[0] != BOS_ID:
            bos_pos0_pass = False

        # Check padding exclusion: token==0 must have mask==0
        pad_indices = np.where(s == PAD_ID)[0]
        if len(pad_indices) > 0:
            if np.any(m[pad_indices] != 0):
                pad_exclusion_pass = False
            # Check padding is suffix only
            first_pad = pad_indices[0]
            if np.any(s[first_pad:] != PAD_ID):
                pad_suffix_pass = False

        # Check user token is never masked
        user_indices = np.where(s == USER_ID)[0]
        if len(user_indices) > 0 and np.any(m[user_indices] != 0):
            user_unmasked_pass = False

        # Check EOS tokens generated by assistant have mask == 1
        eos_indices = np.where(s == EOS_ID)[0]
        for e in eos_indices:
            if m[e] != 1:
                eos_supervised_pass = False
            # Check token right after EOS has mask == 0
            if e + 1 < CONTEXT_LENGTH:
                if s[e + 1] != PAD_ID and s[e + 1] == USER_ID and m[e + 1] != 0:
                    eos_supervised_pass = False

        # Check shifted alignment (input=s[:-1], target=s[1:], loss_mask=m[1:])
        inp = s[:-1]
        tgt = s[1:]
        l_msk = m[1:]

        # Wherever loss_mask == 1, target must not be USER_ID or PAD_ID
        active_targets = tgt[l_msk == 1]
        if np.any(active_targets == USER_ID) or np.any(active_targets == PAD_ID):
            shifted_alignment_pass = False

    checks.append({
        "check": "BOS at Position 0 in all sequences",
        "passed": bos_pos0_pass,
        "details": f"Checked {num_samples_to_check} sequences"
    })
    checks.append({
        "check": "Padding Suffix & Zero Masking",
        "passed": pad_exclusion_pass and pad_suffix_pass,
        "details": "All PAD=0 tokens have mask=0 and appear strictly as trailing suffixes"
    })
    checks.append({
        "check": "Prompt & User Tokens Unsupervised",
        "passed": user_unmasked_pass,
        "details": "All <|user|> tokens have mask=0"
    })
    checks.append({
        "check": "Assistant Turn Boundaries & EOS Supervision",
        "passed": eos_supervised_pass,
        "details": "All assistant-generated EOS tokens have mask=1; subsequent tokens have mask=0"
    })
    checks.append({
        "check": "Shifted Next-Token Loss Mask Alignment",
        "passed": shifted_alignment_pass,
        "details": "loss_mask=1 strictly targets assistant tokens or EOS, never user prompts or padding"
    })

    print(f"[{'PASS' if bos_pos0_pass else 'FAIL'}] BOS at pos 0 verified across {num_samples_to_check} sequences")
    print(f"[{'PASS' if pad_exclusion_pass and pad_suffix_pass else 'FAIL'}] Padding suffix integrity & zero-mask verified")
    print(f"[{'PASS' if user_unmasked_pass else 'FAIL'}] User prompt tokens strictly unmasked (mask=0)")
    print(f"[{'PASS' if eos_supervised_pass else 'FAIL'}] Every assistant turn ends with supervised EOS (mask=1)")
    print(f"[{'PASS' if shifted_alignment_pass else 'FAIL'}] Shifted next-token loss alignment strictly verified")

    all_passed = all(c["passed"] for c in checks)
    return checks, all_passed

def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    print("Loading tokenizer from:", TOKENIZER_PATH)
    tokenizer = Tokenizer.from_file(str(TOKENIZER_PATH))

    # Process train and validation
    train_stats, train_trees = process_paths_file(
        TRAIN_SOURCE, TRAIN_TOKENS_OUT, TRAIN_MASK_OUT, "train", tokenizer
    )
    print()
    val_stats, val_trees = process_paths_file(
        VAL_SOURCE, VAL_TOKENS_OUT, VAL_MASK_OUT, "validation", tokenizer
    )

    # Run automated checks
    checks, all_passed = run_automated_checks(train_stats, val_stats, train_trees, val_trees)

    metadata = {
        "dataset_name": "training_sequences_eos_v2",
        "format_version": "EOS_v2",
        "description": "Clean Design A format with explicit [EOS] at the end of EVERY completed assistant turn. Trailing unanswered user turns trimmed to the last assistant completion. Zero cross-conversation contamination.",
        "created_at": datetime.now().isoformat(),
        "created_by_script": "src/build_eos_v2_sequences.py",
        "context_length": CONTEXT_LENGTH,
        "vocab_size": VOCAB_SIZE,
        "special_tokens": {
            "PAD": PAD_ID,
            "UNK": UNK_ID,
            "BOS": BOS_ID,
            "EOS": EOS_ID,
            "USER": USER_ID,
            "ASSISTANT": ASSISTANT_ID
        },
        "token_dtype": "uint16",
        "mask_dtype": "uint8",
        "source_files": {
            "train": str(TRAIN_SOURCE),
            "validation": str(VAL_SOURCE)
        },
        "output_files": {
            "train_tokens": str(TRAIN_TOKENS_OUT),
            "train_mask": str(TRAIN_MASK_OUT),
            "validation_tokens": str(VAL_TOKENS_OUT),
            "validation_mask": str(VAL_MASK_OUT)
        },
        "train_statistics": train_stats,
        "validation_statistics": val_stats,
        "automated_checks": {
            "all_passed": all_passed,
            "checks": checks
        }
    }

    print()
    print(f"Writing dataset metadata to: {METADATA_OUT}")
    with open(METADATA_OUT, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)

    print("\nEOS v2 dataset creation and validation complete!")
    if all_passed:
        print("ALL AUTOMATED INTEGRITY CHECKS PASSED.")
    else:
        print("WARNING: SOME CHECKS FAILED. See metadata for details.")

if __name__ == "__main__":
    main()
